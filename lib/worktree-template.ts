// Generates an idempotent `scripts/worktree-setup.sh` tailored to a repository's stack.
// Copies missing ignored .env* files (including monorepo subfolders) from the primary worktree,
// writes a deterministic worktree-unique PORT into .env.worktree, and installs dependencies.
import { existsSync } from "node:fs";
import { join } from "node:path";

export type RepoStack = "pnpm" | "bun" | "yarn" | "npm" | "go" | "python" | "generic";

export function detectRepoStack(repoRoot: string): RepoStack {
	if (existsSync(join(repoRoot, "pnpm-lock.yaml"))) return "pnpm";
	if (existsSync(join(repoRoot, "bun.lock")) || existsSync(join(repoRoot, "bun.lockb"))) return "bun";
	if (existsSync(join(repoRoot, "yarn.lock"))) return "yarn";
	if (existsSync(join(repoRoot, "package.json"))) return "npm";
	if (existsSync(join(repoRoot, "go.mod"))) return "go";
	if (existsSync(join(repoRoot, "pyproject.toml")) || existsSync(join(repoRoot, "requirements.txt"))) return "python";
	return "generic";
}

function installSnippet(stack: RepoStack): string {
	switch (stack) {
		case "pnpm":
			return [
				'if [ -f package.json ] && [ ! -d node_modules ]; then',
				'  echo "==> installing dependencies (pnpm)"',
				'  pnpm install --frozen-lockfile',
				'fi',
			].join("\n");
		case "bun":
			return [
				'if [ -f package.json ] && [ ! -d node_modules ]; then',
				'  echo "==> installing dependencies (bun)"',
				'  bun install --frozen-lockfile',
				'fi',
			].join("\n");
		case "yarn":
			return [
				'if [ -f package.json ] && [ ! -d node_modules ]; then',
				'  echo "==> installing dependencies (yarn)"',
				'  yarn install --frozen-lockfile',
				'fi',
			].join("\n");
		case "npm":
			return [
				'if [ -f package.json ] && [ ! -d node_modules ]; then',
				'  echo "==> installing dependencies (npm)"',
				'  if [ -f package-lock.json ]; then npm ci; else npm install; fi',
				'fi',
			].join("\n");
		case "go":
			return [
				'if [ -f go.mod ]; then',
				'  echo "==> downloading Go modules"',
				'  go mod download',
				'fi',
			].join("\n");
		case "python":
			return [
				'if command -v uv >/dev/null 2>&1 && [ -f uv.lock ]; then',
				'  echo "==> syncing Python environment (uv)"',
				'  uv sync',
				'fi',
			].join("\n");
		default:
			return "# Add repo-specific dependency setup here if needed.";
	}
}

export function generateWorktreeSetupScript(repoRoot: string): string {
	const stack = detectRepoStack(repoRoot);
	return `#!/usr/bin/env bash
# Generated by repo-doctor. Safe to run again in any git worktree.
# Copies missing ignored .env* files from the primary checkout, writes a worktree-unique PORT
# to .env.worktree (source it before starting a dev server), and installs dependencies.
set -euo pipefail

WT_ROOT="$(git rev-parse --show-toplevel)"
MAIN_ROOT="$(git worktree list --porcelain | awk '/^worktree /{sub(/^worktree /,""); print; exit}')"

cd "$WT_ROOT"

# 1. Copy missing ignored .env* files (including nested app folders) from the primary worktree.
if [ -n "$MAIN_ROOT" ] && [ "$MAIN_ROOT" != "$WT_ROOT" ]; then
  while IFS= read -r -d '' rel_env; do
    case "$rel_env" in
      .env.worktree|*/.env.worktree|node_modules/*|*/node_modules/*|.git/*) continue ;;
    esac
    if [ -f "$MAIN_ROOT/$rel_env" ] && [ ! -e "$WT_ROOT/$rel_env" ]; then
      mkdir -p "$(dirname "$WT_ROOT/$rel_env")"
      cp "$MAIN_ROOT/$rel_env" "$WT_ROOT/$rel_env"
      echo "==> copied $rel_env from primary worktree"
    fi
  done < <(git -C "$MAIN_ROOT" ls-files --others --ignored --exclude-standard -z -- ':(glob)**/.env*' '.env*')
fi

# 2. Write a deterministic worktree-unique PORT (3100-3999) into .env.worktree.
WT_NAME="$(basename "$WT_ROOT")"
HASH="$(printf '%s' "$WT_NAME" | cksum | awk '{print $1}')"
WT_PORT=$((3100 + (HASH % 900)))
cat > "$WT_ROOT/.env.worktree" <<EOF
# Auto-generated by scripts/worktree-setup.sh for worktree: $WT_NAME
# Load before starting a dev server: set -a; . ./.env.worktree; set +a
PORT=$WT_PORT
EOF
echo "==> wrote .env.worktree (PORT=$WT_PORT; load with: set -a; . ./.env.worktree; set +a)"

# 3. Install dependencies when missing.
${installSnippet(stack)}

echo "Worktree ready: $WT_ROOT (PORT=$WT_PORT)"
`;
}
